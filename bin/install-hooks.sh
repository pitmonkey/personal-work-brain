#!/usr/bin/env bash
#
# install-hooks.sh — install a pre-commit hook that runs the strict OKF linter
# and, when available, a secret scan over the staged diff.
#
# The hook blocks a commit whenever a scanned concept fails conformance
# (missing frontmatter / type, or a misplaced okf_version), or whenever a
# secret scanner flags the staged content. Run from anywhere inside the repo.

set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
HOOK_DIR="$ROOT/.git/hooks"
HOOK="$HOOK_DIR/pre-commit"

mkdir -p "$HOOK_DIR"

cat > "$HOOK" <<'EOF'
#!/usr/bin/env bash
# Pre-commit: OKF conformance gate + secret scan. Generated by bin/install-hooks.sh.
set -uo pipefail
ROOT="$(git rev-parse --show-toplevel)"

# 1. OKF conformance — blocking.
"$ROOT/bin/okf-lint.sh" --strict || exit 1

# 2. Secret scan over staged content — blocking when a scanner is installed.
#    raw/ is immutable and committed, so a secret that lands here is in history
#    for good. This is the last cheap place to stop one.
if command -v gitleaks >/dev/null 2>&1; then
  gitleaks protect --staged --redact --no-banner || {
    echo "pre-commit: gitleaks flagged staged content — commit blocked." >&2
    exit 1
  }
elif command -v trufflehog >/dev/null 2>&1; then
  trufflehog git "file://$ROOT" --since-commit HEAD --only-verified --fail --no-update || {
    echo "pre-commit: trufflehog flagged staged content — commit blocked." >&2
    exit 1
  }
else
  echo "pre-commit: WARNING — no secret scanner found (install gitleaks or trufflehog)." >&2
  echo "pre-commit: conformance passed, but staged content was NOT scanned for secrets." >&2
fi

exit 0
EOF

chmod +x "$HOOK"
chmod +x "$ROOT/bin/okf-lint.sh"

echo "Installed pre-commit hook -> $HOOK"
echo "It runs: bin/okf-lint.sh --strict, then gitleaks/trufflehog on staged content."
if ! command -v gitleaks >/dev/null 2>&1 && ! command -v trufflehog >/dev/null 2>&1; then
  echo
  echo "NOTE: no secret scanner installed. The hook will warn but not scan."
  echo "      Install one:  brew install gitleaks   |   https://github.com/gitleaks/gitleaks"
fi
